package com.linagora.calendar.dav.dto;

import java.net.URI;

import org.apache.http.HttpStatus;

public record CalendarMultiGetEntry(URI href, int status, String calendarData) {

    public boolean isNotFound() {
        return status == HttpStatus.SC_NOT_FOUND;
    }

    public boolean isSuccessful() {
        return status == HttpStatus.SC_OK && !calendarData.isBlank();
    }
}
